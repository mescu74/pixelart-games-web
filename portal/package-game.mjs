import {cp,mkdir,rm} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url))),out=path.join(root,'portal/bundled/ba-invaders');
await rm(out,{recursive:true,force:true});await mkdir(out,{recursive:true});
for(const name of ['index.html','style.css','game.js','core.js','assets.js','street-navigation.js','map-data.json','assets','vendor'])await cp(path.join(root,name),path.join(out,name),{recursive:true});
const platformer=path.join(root,'portal/games/salto-del-sur');
const platformerOut=path.join(root,'portal/bundled/salto-del-sur');
await rm(platformerOut,{recursive:true,force:true});await mkdir(platformerOut,{recursive:true});
for(const name of ['index.html','game.js','characters-crisp.png','pampas-background-fine.png'])await cp(path.join(platformer,name),path.join(platformerOut,name));
const platformerPublic=path.join(platformerOut,'public');await mkdir(platformerPublic,{recursive:true});
for(const name of ['characters-crisp.png','pampas-background-fine.png'])await cp(path.join(platformer,name),path.join(platformerPublic,name));
const puzzle=path.join(root,'portal/games/mudanza-portena'),puzzleOut=path.join(root,'portal/bundled/mudanza-portena');
await rm(puzzleOut,{recursive:true,force:true});await mkdir(path.join(puzzleOut,'public'),{recursive:true});
for(const name of ['index.html','game.js','scene.png'])await cp(path.join(puzzle,name),path.join(puzzleOut,name));
await cp(path.join(puzzle,'scene.png'),path.join(puzzleOut,'public','scene.png'));
console.log('Bundled BA Invaders, Salto del Sur and Mudanza Porteña with original pixel art.');
